package com.eymen.browser.telefon

import android.app.Activity
import android.app.AlertDialog
import android.content.ContentValues
import android.content.Intent
import android.net.Uri
import android.os.Build
import android.os.Environment
import android.provider.MediaStore
import android.widget.Toast
import androidx.activity.ComponentActivity
import androidx.activity.result.contract.ActivityResultContracts
import org.mozilla.geckoview.WebResponse
import java.io.IOException
import java.io.InputStream
import java.net.URLDecoder
import java.util.Locale
import java.util.concurrent.Executors

/**
 * Stage 1 ONLY: consume GeckoView's original download InputStream.
 * PDFs generated by GeckoView's built-in viewer may have a local/blob URI,
 * so do not start a second network request for response.uri.
 *
 * Android 10+: stream directly into Downloads via MediaStore with IS_PENDING.
 * Android 8-9: let the user choose a save location through SAF.
 */
internal class AndroidDownloadDenemesi(private val activity: ComponentActivity) {
    private data class Pending(
        val fileName: String,
        val mimeType: String,
        val body: InputStream
    )

    private val worker = Executors.newSingleThreadExecutor()
    private var choosing: Pending? = null
    private var saveAs: Pending? = null
    private var busy = false

    private val documentPicker = activity.registerForActivityResult(
        ActivityResultContracts.StartActivityForResult()
    ) { result ->
        val request = saveAs.also { saveAs = null } ?: return@registerForActivityResult
        val destination = if (result.resultCode == Activity.RESULT_OK) {
            result.data?.data
        } else null
        if (destination == null) {
            request.body.closeSafely()
            busy = false
            message(R.string.download_cancelled)
        } else {
            writeInBackground(request, destination)
        }
    }

    fun handleResponse(response: WebResponse) {
        val body = response.body
        if (body == null) {
            message(R.string.download_missing)
            return
        }
        if (busy || activity.isFinishing || activity.isDestroyed) {
            body.closeSafely()
            if (busy) message(R.string.download_busy)
            return
        }
        val mime = header(response, "content-type")
            ?.substringBefore(';')?.trim()?.takeIf { it.isNotBlank() }
            ?: if (response.uri.substringBefore('?').endsWith(".pdf", true)) {
                "application/pdf"
            } else "application/octet-stream"

        val filename = safeName(response, mime)
        val request = Pending(filename, mime, body)
        busy = true
        choosing = request
        try {
            AlertDialog.Builder(activity)
                .setTitle(R.string.download_confirm_title)
                .setMessage(activity.getString(R.string.download_confirm_message, filename))
                .setPositiveButton(R.string.download_confirm_allow) { _, _ ->
                    choosing = null
                    if (Build.VERSION.SDK_INT >= Build.VERSION_CODES.Q) {
                        writeInBackground(request, null)
                    } else {
                        saveAs = request
                        val selectFile = Intent(Intent.ACTION_CREATE_DOCUMENT).apply {
                            addCategory(Intent.CATEGORY_OPENABLE)
                            type = mime
                            putExtra(Intent.EXTRA_TITLE, filename)
                        }
                        try {
                            documentPicker.launch(selectFile)
                        } catch (_: Exception) {
                            saveAs = null
                            request.body.closeSafely()
                            busy = false
                            message(R.string.download_failed)
                        }
                    }
                }
                .setNegativeButton(R.string.download_confirm_deny) { _, _ ->
                    choosing = null
                    request.body.closeSafely()
                    busy = false
                }
                .setOnCancelListener {
                    choosing = null
                    request.body.closeSafely()
                    busy = false
                }
                .show()
        } catch (_: Exception) {
            choosing = null
            request.body.closeSafely()
            busy = false
            message(R.string.download_failed)
        }
    }

    private fun writeInBackground(request: Pending, userPickedUri: Uri?) {
        val resolver = activity.applicationContext.contentResolver
        worker.execute {
            var createdDownload: Uri? = null
            try {
                val destination = if (userPickedUri != null) {
                    userPickedUri
                } else {
                    check(Build.VERSION.SDK_INT >= Build.VERSION_CODES.Q)
                    val values = ContentValues().apply {
                        put(MediaStore.MediaColumns.DISPLAY_NAME, request.fileName)
                        put(MediaStore.MediaColumns.MIME_TYPE, request.mimeType)
                        put(MediaStore.MediaColumns.RELATIVE_PATH, Environment.DIRECTORY_DOWNLOADS)
                        put(MediaStore.MediaColumns.IS_PENDING, 1)
                    }
                    val collection = MediaStore.Downloads.getContentUri(
                        MediaStore.VOLUME_EXTERNAL_PRIMARY
                    )
                    (resolver.insert(collection, values)
                        ?: throw IOException("Could not create Downloads entry")).also {
                        createdDownload = it
                    }
                }
                val bytes = request.body.use { source ->
                    (resolver.openOutputStream(destination, "w")
                        ?: throw IOException("Could not open destination")).use { output ->
                        source.copyTo(output, bufferSize = 64 * 1024)
                    }
                }
                if (bytes <= 0L) throw IOException("Empty response")

                createdDownload?.let { downloadUri ->
                    val publish = ContentValues().apply {
                        put(MediaStore.MediaColumns.IS_PENDING, 0)
                    }
                    check(resolver.update(downloadUri, publish, null, null) > 0)
                }

                activity.runOnUiThread {
                    busy = false
                    message(R.string.download_saved, request.fileName)
                }
            } catch (_: Exception) {
                request.body.closeSafely()
                createdDownload?.let { downloadUri ->
                    try { resolver.delete(downloadUri, null, null) } catch (_: Exception) {}
                }
                activity.runOnUiThread {
                    busy = false
                    message(R.string.download_failed)
                }
            }
        }
    }

    private fun safeName(response: WebResponse, mime: String): String {
        val disposition = header(response, "content-disposition").orEmpty()
        val encoded = Regex(
            """filename\*\s*=\s*(?:UTF-8''|"?)([^";]+)""",
            RegexOption.IGNORE_CASE
        ).find(disposition)?.groupValues?.getOrNull(1)?.let {
            try { URLDecoder.decode(it, "UTF-8") } catch (_: Exception) { null }
        }
        val standard = Regex(
            """filename\s*=\s*(?:"([^"]+)"|([^;]+))""",
            RegexOption.IGNORE_CASE
        ).find(disposition)?.groupValues?.drop(1)?.firstOrNull { it.isNotBlank() }
        val fromUri = try { Uri.parse(response.uri).lastPathSegment } catch (_: Exception) { null }
        val suggested = encoded ?: standard ?: fromUri ?: if (mime == "application/pdf") {
            "document.pdf"
        } else "download"
        val cleaned = suggested.substringAfterLast('/').substringAfterLast('\\')
            .replace(Regex("""[\p{Cntrl}:*?"<>|]"""), "_")
            .trim().trim('.', ' ').take(120)
            .ifBlank { if (mime == "application/pdf") "document.pdf" else "download" }
        return if (mime == "application/pdf" &&
            !cleaned.lowercase(Locale.ROOT).endsWith(".pdf")) {
            cleaned + ".pdf"
        } else cleaned
    }

    private fun header(response: WebResponse, key: String): String? =
        response.headers.entries.firstOrNull { it.key.equals(key, ignoreCase = true) }?.value

    private fun InputStream.closeSafely() {
        try { close() } catch (_: Exception) {}
    }

    private fun message(resId: Int, vararg args: Any) {
        if (activity.isFinishing || activity.isDestroyed) return
        Toast.makeText(activity, activity.getString(resId, *args), Toast.LENGTH_LONG).show()
    }

    fun dispose() {
        choosing?.body?.closeSafely()
        choosing = null
        saveAs?.body?.closeSafely()
        saveAs = null
        worker.shutdown()
    }
}
