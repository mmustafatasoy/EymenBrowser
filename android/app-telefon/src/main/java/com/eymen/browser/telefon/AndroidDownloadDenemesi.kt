package com.eymen.browser.telefon

import android.app.Activity
import android.app.AlertDialog
import android.content.ContentValues
import android.content.Intent
import android.net.Uri
import android.os.Build
import android.os.Environment
import android.provider.DocumentsContract
import android.provider.MediaStore
import android.widget.Toast
import androidx.activity.ComponentActivity
import androidx.activity.result.contract.ActivityResultContracts
import org.mozilla.geckoview.WebResponse
import java.io.IOException
import java.io.InputStream
import java.io.OutputStream
import java.net.URLDecoder
import java.util.Locale
import java.util.concurrent.Executors
import java.util.concurrent.CancellationException
import java.util.concurrent.atomic.AtomicBoolean

/**
 * Stage 1 ONLY: consume GeckoView's original download InputStream.
 * PDFs generated by GeckoView's built-in viewer may have a local/blob URI,
 * so do not start a second network request for response.uri.
 *
 * Android 10+: stream directly into Downloads via MediaStore with IS_PENDING.
 * Android 8-9: let the user choose a save location through SAF.
 */
internal class AndroidDownloadDenemesi(
    private val activity: ComponentActivity,
    private val onProgress: (ActiveDownload?) -> Unit = {},
    private val onCompleted: (SavedDownload) -> Unit = {}
) {
    private data class Pending(
        val fileName: String,
        val mimeType: String,
        val body: InputStream,
        val expectedBytes: Long? = null
    )

    private val worker = Executors.newSingleThreadExecutor()
    // Activity is not attached to a Context during its property initialization.
    // The first download is only handled after onCreate; defer Context access.
    private val registry by lazy { DownloadRegistry(activity.applicationContext) }
    private var choosing: Pending? = null
    private var saveAs: Pending? = null
    private var busy = false
    private val cancelled = AtomicBoolean(false)
    @Volatile private var activeBody: InputStream? = null
    @Volatile private var lastProgress: ActiveDownload? = null

    /** Cancel the current transfer; never show a fake successful download. */
    fun cancelActive() {
        if (lastProgress == null) return
        cancelled.set(true)
        lastProgress?.let { publishProgress(it.copy(cancelling = true)) }
        // Closing the GeckoView stream can wake a blocked network read.
        activeBody?.closeSafely()
    }

    private fun publishProgress(progress: ActiveDownload?) {
        lastProgress = progress
        activity.runOnUiThread {
            if (!activity.isFinishing && !activity.isDestroyed) onProgress(progress)
        }
    }

    private val documentPicker = activity.registerForActivityResult(
        ActivityResultContracts.StartActivityForResult()
    ) { result ->
        val request = saveAs.also { saveAs = null } ?: return@registerForActivityResult
        val destination = if (result.resultCode == Activity.RESULT_OK) {
            result.data?.data
        } else null
        if (destination == null) {
            request.body.closeSafely()
            busy = false
            message(R.string.download_cancelled)
        } else {
            try {
                activity.contentResolver.takePersistableUriPermission(
                    destination, Intent.FLAG_GRANT_READ_URI_PERMISSION
                )
            } catch (_: SecurityException) {
                // Not all SAF providers allow persistence; saving still proceeds.
            }
            writeInBackground(request, destination)
        }
    }

    fun handleResponse(response: WebResponse) {
        val body = response.body
        if (body == null) {
            message(R.string.download_missing)
            return
        }
        if (busy || activity.isFinishing || activity.isDestroyed) {
            body.closeSafely()
            if (busy) message(R.string.download_busy)
            return
        }
        val mime = header(response, "content-type")
            ?.substringBefore(';')?.trim()?.takeIf { it.isNotBlank() }
            ?: if (response.uri.substringBefore('?').endsWith(".pdf", true)) {
                "application/pdf"
            } else "application/octet-stream"

        val filename = safeName(response, mime)
        val total = header(response, "content-length")?.trim()
            ?.toLongOrNull()?.takeIf { it > 0 }
        offerDownload(Pending(filename, mime, body, total))
    }

    /** Native GeckoSession.saveAsPdf() supplies the original PDF stream. */
    fun savePdfStream(stream: InputStream) {
        offerDownload(Pending(
            "EymenBrowser-" + System.currentTimeMillis() + ".pdf",
            "application/pdf", stream
        ))
    }

    private fun offerDownload(request: Pending) {
        if (busy || activity.isFinishing || activity.isDestroyed) {
            request.body.closeSafely()
            if (busy) message(R.string.download_busy)
            return
        }
        busy = true
        choosing = request
        try {
            AlertDialog.Builder(activity)
                .setTitle(R.string.download_confirm_title)
                .setMessage(activity.getString(R.string.download_confirm_message, request.fileName))
                .setPositiveButton(R.string.download_confirm_allow) { _, _ ->
                    choosing = null
                    if (Build.VERSION.SDK_INT >= Build.VERSION_CODES.Q) {
                        writeInBackground(request, null)
                    } else {
                        saveAs = request
                        val selectFile = Intent(Intent.ACTION_CREATE_DOCUMENT).apply {
                            addCategory(Intent.CATEGORY_OPENABLE)
                            type = request.mimeType
                            putExtra(Intent.EXTRA_TITLE, request.fileName)
                        }
                        try {
                            documentPicker.launch(selectFile)
                        } catch (_: Exception) {
                            saveAs = null
                            request.body.closeSafely()
                            busy = false
                            message(R.string.download_failed)
                        }
                    }
                }
                .setNegativeButton(R.string.download_confirm_deny) { _, _ ->
                    choosing = null
                    request.body.closeSafely()
                    busy = false
                }
                .setOnCancelListener {
                    choosing = null
                    request.body.closeSafely()
                    busy = false
                }
                .show()
        } catch (_: Exception) {
            choosing = null
            request.body.closeSafely()
            busy = false
            message(R.string.download_failed)
        }
    }

    /**
     * Only bytes ACTUALLY copied from the Gecko WebResponse body are reported.
     * Progress is throttled to avoid excessive Compose/UI updates.
     */
    private fun copyWithProgress(
        source: InputStream, output: OutputStream, request: Pending
    ): Long {
        val buffer = ByteArray(64 * 1024)
        var written = 0L
        var lastUpdate = 0L
        while (true) {
            if (cancelled.get()) throw CancellationException("User cancelled")
            val count = source.read(buffer)
            if (count < 0) break
            if (count == 0) continue
            if (cancelled.get()) throw CancellationException("User cancelled")
            output.write(buffer, 0, count)
            written += count
            val now = android.os.SystemClock.elapsedRealtime()
            if (now - lastUpdate >= 150L) {
                publishProgress(ActiveDownload(request.fileName, written, request.expectedBytes))
                lastUpdate = now
            }
        }
        if (cancelled.get()) throw CancellationException("User cancelled")
        output.flush()
        publishProgress(ActiveDownload(request.fileName, written, request.expectedBytes))
        return written
    }

    private fun writeInBackground(request: Pending, userPickedUri: Uri?) {
        val resolver = activity.applicationContext.contentResolver
        cancelled.set(false)
        worker.execute {
            var createdDownload: Uri? = null
            var cancelledByUser = false
            activeBody = request.body
            publishProgress(ActiveDownload(request.fileName, 0L, request.expectedBytes))
            try {
                if (cancelled.get()) throw CancellationException("User cancelled")
                val destination = if (userPickedUri != null) {
                    userPickedUri
                } else {
                    check(Build.VERSION.SDK_INT >= Build.VERSION_CODES.Q)
                    val values = ContentValues().apply {
                        put(MediaStore.MediaColumns.DISPLAY_NAME, request.fileName)
                        put(MediaStore.MediaColumns.MIME_TYPE, request.mimeType)
                        put(MediaStore.MediaColumns.RELATIVE_PATH, Environment.DIRECTORY_DOWNLOADS)
                        put(MediaStore.MediaColumns.IS_PENDING, 1)
                    }
                    val collection = MediaStore.Downloads.getContentUri(
                        MediaStore.VOLUME_EXTERNAL_PRIMARY
                    )
                    (resolver.insert(collection, values)
                        ?: throw IOException("Could not create Downloads entry")).also {
                        createdDownload = it
                    }
                }
                val bytes = request.body.use { source ->
                    (resolver.openOutputStream(destination, "w")
                        ?: throw IOException("Could not open destination")).use { output ->
                        copyWithProgress(source, output, request)
                    }
                }
                if (bytes <= 0L) throw IOException("Empty response")
                if (cancelled.get()) throw CancellationException("User cancelled")

                createdDownload?.let { downloadUri ->
                    val publish = ContentValues().apply {
                        put(MediaStore.MediaColumns.IS_PENDING, 0)
                    }
                    check(resolver.update(downloadUri, publish, null, null) > 0)
                }

                val completed = SavedDownload(
                    uri = destination.toString(),
                    name = request.fileName,
                    mimeType = request.mimeType,
                    bytes = bytes,
                    savedAt = System.currentTimeMillis()
                )
                try {
                    registry.record(completed)
                } catch (_: Exception) {
                    // Saved file remains valid even when history cannot persist.
                }
                activity.runOnUiThread {
                    if (!activity.isFinishing && !activity.isDestroyed) {
                        onCompleted(completed)
                        message(R.string.download_saved, request.fileName)
                    }
                }
            } catch (error: Exception) {
                cancelledByUser = cancelled.get() || error is CancellationException
                request.body.closeSafely()
                createdDownload?.let { downloadUri ->
                    // Pending MediaStore content is never published after failure.
                    try { resolver.delete(downloadUri, null, null) } catch (_: Exception) {}
                }
                if (cancelledByUser && userPickedUri != null) {
                    // ACTION_CREATE_DOCUMENT creates a user-chosen new document.
                    // Best-effort removal of incomplete output; provider may
                    // reject deletion, so never claim it was always removed.
                    try { DocumentsContract.deleteDocument(resolver, userPickedUri) }
                    catch (_: Exception) {}
                }
                activity.runOnUiThread {
                    if (!activity.isFinishing && !activity.isDestroyed) {
                        message(
                            if (cancelledByUser) R.string.download_cancelled
                            else R.string.download_failed
                        )
                    }
                }
            } finally {
                activeBody = null
                lastProgress = null
                activity.runOnUiThread {
                    busy = false
                    if (!activity.isFinishing && !activity.isDestroyed) onProgress(null)
                }
            }
        }
    }

    private fun safeName(response: WebResponse, mime: String): String {
        val disposition = header(response, "content-disposition").orEmpty()
        val encoded = Regex(
            """filename\*\s*=\s*(?:UTF-8''|"?)([^";]+)""",
            RegexOption.IGNORE_CASE
        ).find(disposition)?.groupValues?.getOrNull(1)?.let {
            try { URLDecoder.decode(it, "UTF-8") } catch (_: Exception) { null }
        }
        val standard = Regex(
            """filename\s*=\s*(?:"([^"]+)"|([^;]+))""",
            RegexOption.IGNORE_CASE
        ).find(disposition)?.groupValues?.drop(1)?.firstOrNull { it.isNotBlank() }
        val fromUri = try { Uri.parse(response.uri).lastPathSegment } catch (_: Exception) { null }
        val suggested = encoded ?: standard ?: fromUri ?: if (mime == "application/pdf") {
            "document.pdf"
        } else "download"
        val cleaned = suggested.substringAfterLast('/').substringAfterLast('\\')
            .replace(Regex("""[\p{Cntrl}:*?"<>|]"""), "_")
            .trim().trim('.', ' ').take(120)
            .ifBlank { if (mime == "application/pdf") "document.pdf" else "download" }
        return if (mime == "application/pdf" &&
            !cleaned.lowercase(Locale.ROOT).endsWith(".pdf")) {
            cleaned + ".pdf"
        } else cleaned
    }

    private fun header(response: WebResponse, key: String): String? =
        response.headers.entries.firstOrNull { it.key.equals(key, ignoreCase = true) }?.value

    private fun InputStream.closeSafely() {
        try { close() } catch (_: Exception) {}
    }

    private fun message(resId: Int, vararg args: Any) {
        if (activity.isFinishing || activity.isDestroyed) return
        Toast.makeText(activity, activity.getString(resId, *args), Toast.LENGTH_LONG).show()
    }

    fun dispose() {
        cancelled.set(true)
        activeBody?.closeSafely()
        choosing?.body?.closeSafely()
        choosing = null
        saveAs?.body?.closeSafely()
        saveAs = null
        worker.shutdownNow()
    }
}
