package com.eymen.browser.telefon

import android.Manifest
import android.content.pm.PackageManager
import android.content.Context
import android.app.Activity
import android.app.AlertDialog
import android.content.Intent
import android.net.Uri
import android.os.Build
import android.widget.Toast
import androidx.activity.ComponentActivity
import androidx.activity.result.contract.ActivityResultContracts
import org.mozilla.geckoview.WebResponse
import java.io.InputStream
import java.net.URLDecoder
import java.util.Locale

/**
 * User consent/SAF adapter: consume GeckoView's original download InputStream.
 * PDFs generated by GeckoView's built-in viewer may have a local/blob URI,
 * so do not start a second network request for response.uri.
 *
 * Android 10+: stream directly into Downloads via MediaStore with IS_PENDING.
 * Android 8-9: let the user choose a save location through SAF.
 */
internal class AndroidDownloadDenemesi(
    private val activity: ComponentActivity,
    private val onProgress: (ActiveDownload?) -> Unit = {},
    private val onCompleted: (SavedDownload) -> Unit = {},
    private val onQueue: (List<QueuedDownload>) -> Unit = {}
) {
    private data class Pending(
        val fileName: String,
        val mimeType: String,
        val body: InputStream,
        val expectedBytes: Long? = null
    )

    // Context access stays lazy until the Activity is attached.
    private val coordinator by lazy { DownloadCoordinator.get(activity.applicationContext) }
    private var choosing: Pending? = null
    private var saveAs: Pending? = null
    private var notificationConsent: Pending? = null
    private var busy = false // only a pending consent/file-picker, not the transfer
    private var observing = false
    private val observer = object : DownloadObserver {
        override fun onSnapshot(snapshot: DownloadSnapshot) {
            if (activity.isFinishing || activity.isDestroyed) return
            onProgress(snapshot.active)
            onQueue(snapshot.queued)
        }
        override fun onCompleted(file: SavedDownload) {
            if (activity.isFinishing || activity.isDestroyed) return
            onCompleted(file)
            message(R.string.download_saved, file.name)
        }
        override fun onMessage(message: Int) { this@AndroidDownloadDenemesi.message(message) }
    }

    fun observe() {
        if (!observing) { observing = true; coordinator.observe(observer) }
    }
    fun pauseObserving() {
        if (observing) { coordinator.unobserve(observer); observing = false }
    }
    fun cancelActive() = coordinator.cancelActive()
    fun cancelQueued(id: Long) = coordinator.cancel(id)

    private val notificationPermission = activity.registerForActivityResult(
        ActivityResultContracts.RequestPermission()
    ) {
        val request = notificationConsent.also { notificationConsent = null }
            ?: return@registerForActivityResult
        if (activity.isFinishing || activity.isDestroyed) {
            request.body.closeSafely()
            busy = false
        } else chooseDestination(request)
    }

    private fun requestNotificationThenSave(request: Pending) {
        val prefs = activity.getSharedPreferences("eymen_download_notifications", Context.MODE_PRIVATE)
        if (Build.VERSION.SDK_INT >= 33 &&
            activity.checkSelfPermission(Manifest.permission.POST_NOTIFICATIONS) != PackageManager.PERMISSION_GRANTED &&
            !prefs.getBoolean("requested", false)) {
            prefs.edit().putBoolean("requested", true).apply()
            notificationConsent = request
            try { notificationPermission.launch(Manifest.permission.POST_NOTIFICATIONS) }
            catch (_: Exception) { notificationConsent = null; chooseDestination(request) }
        } else chooseDestination(request)
    }

    private fun chooseDestination(request: Pending) {
        if (Build.VERSION.SDK_INT >= Build.VERSION_CODES.Q) {
            enqueue(request, null)
        } else {
            saveAs = request
            val selectFile = Intent(Intent.ACTION_CREATE_DOCUMENT).apply {
                addCategory(Intent.CATEGORY_OPENABLE)
                type = request.mimeType
                putExtra(Intent.EXTRA_TITLE, request.fileName)
            }
            try {
                documentPicker.launch(selectFile)
            } catch (_: Exception) {
                saveAs = null
                request.body.closeSafely()
                busy = false
                message(R.string.download_failed)
            }
        }
    }

    private val documentPicker = activity.registerForActivityResult(
        ActivityResultContracts.StartActivityForResult()
    ) { result ->
        val request = saveAs.also { saveAs = null } ?: return@registerForActivityResult
        val destination = if (result.resultCode == Activity.RESULT_OK) {
            result.data?.data
        } else null
        if (destination == null) {
            request.body.closeSafely()
            busy = false
            message(R.string.download_cancelled)
        } else {
            try {
                activity.contentResolver.takePersistableUriPermission(
                    destination, Intent.FLAG_GRANT_READ_URI_PERMISSION
                )
            } catch (_: SecurityException) {
                // Not all SAF providers allow persistence; saving still proceeds.
            }
            enqueue(request, destination)
        }
    }

    fun handleResponse(response: WebResponse) {
        val body = response.body
        if (body == null) {
            message(R.string.download_missing)
            return
        }
        if (busy || activity.isFinishing || activity.isDestroyed) {
            body.closeSafely()
            if (busy) message(R.string.download_busy)
            return
        }
        val mime = header(response, "content-type")
            ?.substringBefore(';')?.trim()?.takeIf { it.isNotBlank() }
            ?: if (response.uri.substringBefore('?').endsWith(".pdf", true)) {
                "application/pdf"
            } else "application/octet-stream"

        val filename = safeName(response, mime)
        val total = header(response, "content-length")?.trim()
            ?.toLongOrNull()?.takeIf { it > 0 }
        offerDownload(Pending(filename, mime, body, total))
    }

    /** Native GeckoSession.saveAsPdf() supplies the original PDF stream. */
    fun savePdfStream(stream: InputStream) {
        offerDownload(Pending(
            "EymenBrowser-" + System.currentTimeMillis() + ".pdf",
            "application/pdf", stream
        ))
    }

    private fun offerDownload(request: Pending) {
        if (busy || activity.isFinishing || activity.isDestroyed) {
            request.body.closeSafely()
            if (busy) message(R.string.download_busy)
            return
        }
        busy = true
        choosing = request
        try {
            BrowserDialogs.builder(activity)
                .setTitle(R.string.download_confirm_title)
                .setMessage(activity.getString(R.string.download_confirm_message, request.fileName))
                .setPositiveButton(R.string.download_confirm_allow) { _, _ ->
                    choosing = null
                    requestNotificationThenSave(request)
                }
                .setNegativeButton(R.string.download_confirm_deny) { _, _ ->
                    choosing = null
                    request.body.closeSafely()
                    busy = false
                }
                .setOnCancelListener {
                    choosing = null
                    request.body.closeSafely()
                    busy = false
                }
                .show()
        } catch (_: Exception) {
            choosing = null
            request.body.closeSafely()
            busy = false
            message(R.string.download_failed)
        }
    }

    private fun enqueue(request: Pending, destination: Uri?) {
        busy = false
        coordinator.enqueue(request.fileName, request.mimeType, request.body,
            request.expectedBytes, destination)
    }

    private fun safeName(response: WebResponse, mime: String): String {
        val disposition = header(response, "content-disposition").orEmpty()
        val encoded = Regex(
            """filename\*\s*=\s*(?:UTF-8''|"?)([^";]+)""",
            RegexOption.IGNORE_CASE
        ).find(disposition)?.groupValues?.getOrNull(1)?.let {
            try { URLDecoder.decode(it, "UTF-8") } catch (_: Exception) { null }
        }
        val standard = Regex(
            """filename\s*=\s*(?:"([^"]+)"|([^;]+))""",
            RegexOption.IGNORE_CASE
        ).find(disposition)?.groupValues?.drop(1)?.firstOrNull { it.isNotBlank() }
        val fromUri = try { Uri.parse(response.uri).lastPathSegment } catch (_: Exception) { null }
        val suggested = encoded ?: standard ?: fromUri ?: if (mime == "application/pdf") {
            "document.pdf"
        } else "download"
        val cleaned = suggested.substringAfterLast('/').substringAfterLast('\\')
            .replace(Regex("""[\p{Cntrl}:*?"<>|]"""), "_")
            .trim().trim('.', ' ').take(120)
            .ifBlank { if (mime == "application/pdf") "document.pdf" else "download" }
        return if (mime == "application/pdf" &&
            !cleaned.lowercase(Locale.ROOT).endsWith(".pdf")) {
            cleaned + ".pdf"
        } else cleaned
    }

    private fun header(response: WebResponse, key: String): String? =
        response.headers.entries.firstOrNull { it.key.equals(key, ignoreCase = true) }?.value

    private fun InputStream.closeSafely() {
        val body = this
        Thread({ try { body.close() } catch (_: Exception) {} }, "EymenDiscardDownload")
            .apply { isDaemon = true; start() }
    }

    private fun message(resId: Int, vararg args: Any) {
        if (activity.isFinishing || activity.isDestroyed) return
        Toast.makeText(activity, activity.getString(resId, *args), Toast.LENGTH_LONG).show()
    }

    fun dispose() {
        pauseObserving()
        // Confirmed streams belong to the service, not this Activity.
        notificationConsent?.body?.closeSafely()
        notificationConsent = null
        choosing?.body?.closeSafely()
        choosing = null
        saveAs?.body?.closeSafely()
        saveAs = null
        busy = false
    }
}
